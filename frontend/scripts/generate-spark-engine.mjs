// Explicitly extract the existing scoring functions; never ship server credentials or IO.
import ts from "typescript";
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";

const source = await readFile(new URL("../../supabase/functions/murec2-api/index.ts", import.meta.url), "utf8");
const ast = ts.createSourceFile("engine.ts", source, ts.ScriptTarget.Latest, true);
const allowed = new Set([
  "modeWeights", "lyricWeights", "styleFamilies", "providerTaxonomy", "styleAdjacency", "ApiError",
  "cleanTrack", "transientAnchor", "meanScaledDifference", "cosine", "normalizedStyle", "recordingIdentity",
  "normalizedSearchText", "editSimilarity", "fuzzyTokenMatch", "tokenCoverage", "searchRelevance", "preferSearchDuplicate",
  "appleTrack", "styleFamily", "styleSimilarity", "primaryGenre", "genreSimilarity", "titleMood", "vibeSimilarity",
  "weightedScore", "lyricSimilarity", "matchReasons", "transitionTempoDifference", "keyCompatibility", "transitionMetrics",
  "components", "keyNames", "transitionTrack", "bridge", "recommend",
]);
const snippets = [];
for (const node of ast.statements) {
  const name = node.name?.text ?? node.declarationList?.declarations[0]?.name?.text;
  if (!allowed.delete(name)) continue;
  let code = node.getText(ast);
  if (name === "recommend" || name === "bridge") {
    const edits = [];
    for (const statement of node.body.statements) {
      if (!ts.isIfStatement(statement) || statement.expression.getText(ast) !== "context") continue;
      if (statement.getText(ast).includes('from("recommendation_runs")')) {
        edits.push({ start: statement.getStart(ast) - node.getStart(ast), end: statement.end - node.getStart(ast), text: "" });
      } else {
        const select = statement.thenStatement.statements[0];
        if (!select.getText(ast).includes("Promise.all")) throw new Error("Personalization source changed; review generator");
        edits.push({ start: select.getStart(ast) - node.getStart(ast), end: select.end - node.getStart(ast),
          text: "const { favorites = [], interactions = [], items = [] } = context;" });
      }
    }
    for (const edit of edits.sort((a, b) => b.start - a.start)) code = code.slice(0, edit.start) + edit.text + code.slice(edit.end);
  }
  snippets.push(code);
}
if (allowed.size) throw new Error(`Missing engine exports: ${[...allowed]}`);
const body = snippets.join("\n\n");
if (/\b(?:Deno|admin|supabase|fetch|createClient)\b|context\.client/.test(body)) throw new Error("Server-only code leaked into browser engine");
const generated = ts.transpileModule(`
export function createEngine(library) {
const loadLibrary = async () => library;
${body}
return { recommend, bridge, cleanTrack, transientAnchor, searchRelevance, recordingIdentity, normalizedSearchText,
  preferSearchDuplicate, appleTrack, providerTaxonomy, styleFamilies };
}`, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
const hash = createHash("sha256").update(source).digest("hex");
await writeFile(new URL("../src/spark/engine.generated.js", import.meta.url),
  `// Generated by scripts/generate-spark-engine.mjs. Do not hand-edit.\n// Source SHA256: ${hash}\n${generated}`);
console.log("Generated browser scoring engine (server persistence removed; scoring preserved).");
